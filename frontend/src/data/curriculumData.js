/**
 * Returns available grades from the syllabus.
 */
export function getGrades(syllabus = DEFAULT_GRADE_SYLLABUS) {
  return Object.keys(syllabus || DEFAULT_GRADE_SYLLABUS);
}

/**
 * Returns available subjects for a specific grade.
 */
export function getSubjectsForGrade(grade, syllabus = DEFAULT_GRADE_SYLLABUS) {
  const gradeData = syllabus?.[grade] || DEFAULT_GRADE_SYLLABUS[grade];
  if (!gradeData) return ['Mathematics', 'Physics', 'Chemistry'];
  return Object.keys(gradeData);
}

/**
 * Returns available chapters for a specific grade and subject.
 */
export function getChaptersForSubject(grade, subject, syllabus = DEFAULT_GRADE_SYLLABUS) {
  const gradeData = syllabus?.[grade] || DEFAULT_GRADE_SYLLABUS[grade];
  if (gradeData && gradeData[subject]) {
    return Object.keys(gradeData[subject]);
  }
  
  // Fallback: check other grades if this subject exists
  for (const g of Object.keys(syllabus || DEFAULT_GRADE_SYLLABUS)) {
    if (syllabus[g]?.[subject]) {
      return Object.keys(syllabus[g][subject]);
    }
  }
  return ['General Chapter'];
}

/**
 * Returns available topics for a specific grade, subject, and chapter.
 */
export function getTopicsForChapter(grade, subject, chapter, syllabus = DEFAULT_GRADE_SYLLABUS) {
  const gradeData = syllabus?.[grade] || DEFAULT_GRADE_SYLLABUS[grade];
  if (gradeData && gradeData[subject] && gradeData[subject][chapter]) {
    return gradeData[subject][chapter];
  }
  
  // Fallback: search across all grades for matching subject & chapter
  for (const g of Object.keys(syllabus || DEFAULT_GRADE_SYLLABUS)) {
    if (syllabus[g]?.[subject]?.[chapter]) {
      return syllabus[g][subject][chapter];
    }
  }
  return ['Core Concepts'];
}
